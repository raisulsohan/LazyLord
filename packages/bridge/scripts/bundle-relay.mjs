/*
 * Bundle the relay for the Adobe panel.
 *
 * A LazyLord panel runs the bridge itself (the first one opened hosts it), so
 * nobody has to start anything. CEP gives the panel Node, but not this repo's
 * node_modules once the panel folder is linked into Adobe's extensions
 * directory — so the relay, @lazylord/core and ws go in as one file, for the
 * oldest Node a supported host ships. The output is generated; git ignores it.
 */
import { build } from "esbuild";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outfile = resolve(root, "../adobe-cep/js/relay.js");

await build({
  entryPoints: [resolve(root, "src/relay.ts")],
  outfile,
  bundle: true,
  platform: "node",
  format: "cjs",
  target: "node12",
  // ws uses these native speed-ups when they are installed, and works without.
  external: ["bufferutil", "utf-8-validate"],
  banner: { js: "/* GENERATED by packages/bridge/scripts/bundle-relay.mjs — do not edit. */" },
  logLevel: "warning",
});
console.log("bundled packages/adobe-cep/js/relay.js");
